package app.rafiq.domain.model

/**
 * تطبيعُ استعلام البحث العربي — توأمُ `searchable()` في
 * `tools/build_quran_assets.py`.
 *
 * **لماذا وُجد هذا:** كان بحثُ القرآن يعطي صفر نتائج دائماً. الاستعلام
 * يُمرَّر كما كتبه المستخدم إلى `LIKE '%…%'` على عمودٍ فيه التشكيلُ كاملاً
 * بالرسم العثماني — فمن كتب «الله» لم يجد شيئاً، ولا من كتب «الرحمن»،
 * ولا من كتب «الحمد». قِيس: صفرٌ من ٦٢٣٦ صفّاً لكل واحدةٍ منها.
 *
 * والعمودُ الآن مولَّدٌ بهذا التطبيع نفسِه، فيلتقي الطرفان:
 *
 * ١. حذفُ التشكيل وعلامات الوقف والمدّ ورؤوس الآي.
 * ٢. توحيدُ الحروف: أإآٱ ← ا · ى ← ي · ة ← ه · ؤ ← و · ئ ← ي ·
 *    والهمزةُ المفردة تُحذف («ءَامَنُوا۟» يكتبها الناس «آمنوا»).
 * ٣. تصحيحُ الكلمات التي يخالف رسمُها العثمانيّ الإملائيَّ بالواو
 *    («ٱلصَّلَوٰة» ← الصلاة).
 * ٤. حذفُ الألف كلِّها. لأن العثمانيّ يُسقط ألفاتٍ يُثبتها الإملائيّ
 *    ويضع مكانها ألفاً خنجريّة: «ٱلْعَٰلَمِينَ» يكتبها الناس «العالمين».
 *    فلو أُبقيت الألفُ لضاع نصفُ البحث، ولو حُوّلت الخنجريّةُ ألفاً لضاع
 *    النصفُ الآخر («ٱلرَّحْمَٰن» يكتبها الناس «الرحمن» لا «الرحمان»).
 *    وحذفُها من الطرفين يُنهي المسألة.
 * ٥. حذفُ المسافات. الرسمُ العثمانيّ يصل كلماتٍ يفصلها الإملائيّ
 *    («يَٰٓأَيُّهَا» ← «يا أيها»)، فلولا هذا لَما وُجد أشهرُ نداءٍ في القرآن.
 *
 * أيُّ تغييرٍ هنا يجب أن يقع في المولّد كذلك، ثمّ يُعاد تشغيلُه —
 * و`tools/check_quran_data.py` يفشل إن افترقا.
 */
object ArabicSearch {

    /**
     * أقصرُ استعلامٍ مقبول **بعد** التطبيع.
     *
     * ثلاثةٌ لا حرفان: التطبيعُ يُقصّر الكلمة (‏«الماء» تصير «لم»)، واستعلامٌ
     * بحرفين يُطابق آلافَ الآيات فيعطي ضجيجاً لا نتائج.
     */
    const val MIN_QUERY = 3

    private val DIACRITICS = Regex("[\\u0610-\\u061A\\u064B-\\u065F\\u0670\\u06D6-\\u06ED\\u0640]")

    private val LETTERS = mapOf(
        "ٱ" to "ا",  // ٱ همزة الوصل
        "آ" to "ا",
        "أ" to "ا",
        "إ" to "ا",
        "ى" to "ي",
        "ة" to "ه",
        "ؤ" to "و",
        "ئ" to "ي",
        "ء" to "",
    )

    private val UTHMANI_TO_IMLAEI = mapOf(
        "صلوه"   to "صلاه",
        "زكوه"   to "زكاه",
        "حيوه"   to "حياه",
        "مشكوه"  to "مشكاه",
        "منوه"   to "مناه",
        "ربوا"   to "ربا",
        "التورىه" to "التوراه",
    )

    fun normalize(input: String): String {
        var t = DIACRITICS.replace(input, "")
        for ((from, to) in LETTERS) t = t.replace(from, to)
        for ((from, to) in UTHMANI_TO_IMLAEI) t = t.replace(from, to)
        t = t.replace("ا", "")
        return t.filterNot { it.isWhitespace() }
    }

    /** هل يستحقّ هذا الاستعلامُ ضربَ القاعدة؟ */
    fun isSearchable(input: String): Boolean = normalize(input).length >= MIN_QUERY
}
