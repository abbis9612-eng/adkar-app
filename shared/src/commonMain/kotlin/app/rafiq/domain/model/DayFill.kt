/* ═══════════════════════════════════════════════════════════════════
   «كم اكتمل هذا اليوم؟» — سؤالٌ واحد، وجوابٌ واحد.

   كان له ثلاثةُ أجوبةٍ مختلفة في ثلاث شاشات، فيرى صاحبُ اليوم الواحد
   ثلاثةَ أحكامٍ عليه:

     • `DaysGrid.fillOf` — خمسةُ أقسام، والصلواتُ كسرٌ من خمس. (أعدلُها)
     • `ProfileScreen`   — صباحٌ + مساءٌ + عددُ الصلوات، و«مكتمل» عند ٥.
       فمن صلّى الخمسَ ولم يذكر شيئاً يُقال له: يومُك تامّ.
     • `GardenScreen`    — خمسةُ أعمالٍ ثمّ `coerceAtMost(4)`. فالسقفُ ٤،
       أي أنّ **أربعةً من خمسة = «يوم مكتمل»**، ومن لم يصلِّ فرضاً واحداً
       تُهنّئه الحديقةُ بزهرةٍ تامّة. وأسطورتُها تقول «شجرة = أذكار +
       قرآن + صلاة» — وهي لا تنظر إلى تركيب الأعمال أصلاً، بل إلى عددها.

   فالحسابُ هنا، مرّةً واحدة: خمسةُ أعمالٍ متساوية الوزن، والصلواتُ
   وحدَها متدرّجةٌ لأنّها خمسٌ لا واحدة. والنتيجةُ ٠٫٠ إلى ١٫٠، و١٫٠ لا
   تُبلَغ إلّا بالخمسة كلِّها والصلواتِ الخمس.
═══════════════════════════════════════════════════════════════════ */

/** نسبةُ اكتمال اليوم: ٠٫٠ (لا شيء) إلى ١٫٠ (تامّ). */
fun dayFill(p: DailyProgressInfo?): Float {
    if (p == null) return 0f
    var score = 0f
    if (p.morningDone)      score += 1f
    if (p.eveningDone)      score += 1f
    if (p.quranPages   > 0) score += 1f
    if (p.tasbeehCount > 0) score += 1f
    score += p.prayersLogged.coerceIn(0, 5).toFloat() / 5f
    return (score / 5f).coerceIn(0f, 1f)
}

/**
 * هل كان اليومُ نشِطاً؟
 *
 * أيُّ عملٍ من الخمسة يكفي. كان `WeeklyReportScreen` يعدّ الأذكارَ
 * والصلواتِ فقط، فيومٌ قرأتَ فيه عشرين صفحةً «غيرُ نشط» — والشاشةُ
 * نفسُها تتصدّرها تلك الصفحات.
 */
fun isActiveDay(p: DailyProgressInfo?): Boolean =
    p != null && (p.morningDone || p.eveningDone ||
                  p.quranPages > 0 || p.tasbeehCount > 0 || p.prayersLogged > 0)
