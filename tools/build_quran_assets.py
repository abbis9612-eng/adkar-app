#!/usr/bin/env python3
"""
مولّدُ أصول القرآن — يُصلح عطبين في `quran_uthmani.json` ويُبقيه قابلاً
لإعادة التوليد.

يقرأ الملفَّ ويكتبه في مكانه. تشغيلُه مرّتين لا يُغيّر شيئاً (idempotent).

═══ العطب الأوّل: البسملة ملتصقةٌ بأوّل آية ═══

كانت `2:1` نصُّها «بِسْمِ ٱللَّهِ ٱلرَّحْمَٰنِ ٱلرَّحِيمِ الٓمٓ» — والبسملةُ
ليست آيةً من البقرة. وهذا في ١١١ سورة من ١١٤.

والصفحةُ المصحفيةُ بخطّ QCF4 لم تُظهر العطب لأنها ترسم البسملة من محرفٍ
مستقلّ في التخطيط (١١٢ منها). لكنّ نمطَ النصّ، والبحثَ، والنسخَ،
والمشاركةَ، والتفسيرَ — كلَّها كانت تعرض نصّاً قرآنياً خاطئاً.

الاستثناءان الصحيحان:
  · الفاتحة — البسملةُ فيها آيةٌ أولى بالفعل، فتبقى كما هي.
  · التوبة — لا بسملة لها أصلاً.
  · النمل ٣٠ — فيها بسملةٌ داخل الآية (من كتاب سليمان)، وليست في أوّلها،
    فلا يمسّها هذا المولّد لأنه لا يقصّ إلّا من بداية آيةٍ رقمُها ١.

═══ العطب الثاني: البحث يعطي صفر نتائج دائماً ═══

`text_simple` كان اسماً على غير مسمّى: ٦٢٣٥ صفّاً من ٦٢٣٦ فيها التشكيلُ
كاملاً، ولم يكن مجرَّداً إلّا من همزة الوصل. واستعلامُ البحث
`LIKE '%'||:q||'%'` عليه — فمن كتب «الله» أو «الرحمن» لم يجد شيئاً أبداً،
والشاشةُ تنصحه بالكتابة «بلا تشكيل» وهو الشيءُ الوحيد المضمونُ فشلُه.

فيُضاف عمودٌ `text_search` مجرَّدٌ فعلاً: بلا حركات، ولا مدّات، ولا
علامات وقف، وبألفٍ وياءٍ وتاءٍ وهمزاتٍ موحّدة — فيجد من كتب «الرحمن»
«ٱلرَّحْمَٰنِ»، ومن كتب «انا» «إِنَّا».

`text_uthmani` لا يُمسّ. هو النصّ المقروء، ولا يُعدَّل نصٌّ قرآنيّ.
"""
import json
import pathlib
import re
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
QURAN = ROOT / "androidApp/src/main/assets/quran_uthmani.json"

# البسملة بكل صور رسمها العثماني — همزة وصل أو قطع، بمدّة أو بدونها.
BISMILLAH_RE = re.compile(
    r"^\s*ب\S*\s+[ٱا]?ل?ل\S*\s+[ٱا]?ل?ر\S*\s+[ٱا]?ل?ر\S*\s+"
)

#  السورتان اللتان لا يُقصّ منهما:
#  ١ الفاتحة — البسملةُ فيها آيةٌ أولى معدودة.
#  ٩ التوبة  — بلا بسملة أصلاً.
KEEP_WHOLE = {1, 9}

# الحركاتُ وعلاماتُ الوقف والمدّ ورؤوسُ الآي — كلُّها تُحذف من عمود البحث.
DIACRITICS = re.compile(
    "["
    "ؐ-ؚ"   # علامات قرآنية
    "ً-ٟ"   # الحركات والتنوين والسكون
    "ٰ"          # الألف الخنجرية
    "ۖ-ۭ"   # علامات الوقف ورؤوس الآي والصفر
    "ـ"          # التطويل
    "]"
)

TRANSLATE = str.maketrans({
    "ٱ": "ا",  # همزة الوصل
    "آ": "ا",
    "أ": "ا",
    "إ": "ا",
    "ى": "ي",  # الألف المقصورة
    "ة": "ه",  # التاء المربوطة
    "ؤ": "و",
    "ئ": "ي",
    #  الهمزةُ المفردة تُحذف. الرسمُ العثمانيّ يكتب «ءَامَنُوا۟» بهمزةٍ على
    #  السطر، والناسُ يكتبونها «آمنوا». وبدون هذا لا يُوجد أشهرُ نداءٍ في
    #  القرآن: «يا أيها الذين آمنوا».
    "ء": None,
})

#  كلماتٌ رسمُها العثمانيّ يخالف الإملائيّ بالواو لا بالألف، فلا يُصلحها
#  حذفُ الألف. والمستخدم يكتبها إملائيّةً دائماً.
#  تُطبَّق على عمود البحث وعلى استعلام المستخدم معاً، فيلتقيان.
UTHMANI_TO_IMLAEI = {
    "صلوه": "صلاه",
    "زكوه": "زكاه",
    "حيوه": "حياه",
    "مشكوه": "مشكاه",
    "منوه": "مناه",
    "ربوا": "ربا",
    "التورىه": "التوراه",
}


def searchable(text: str) -> str:
    """
    نصٌّ يصلح لـ LIKE على ما يكتبه الناس فعلاً.

    والخطوةُ الأهمّ فيه حذفُ الألف كلِّها. سببُها أنّ الرسم العثماني يُسقط
    ألفاتٍ يُثبتها الإملائيّ ويُثبت ألفاً خنجريّةً مكانها: «ٱلْعَٰلَمِينَ»
    يكتبها الناس «العالمين». فلو أبقينا الألفَ لضاع نصفُ البحث في اتّجاه،
    ولو حوّلنا الخنجريّة ألفاً لضاع النصفُ الآخر («ٱلرَّحْمَٰن» يكتبها
    الناس «الرحمن» لا «الرحمان»). وحذفُها من الطرفين يُنهي المسألة:
    «لرحمن» و«لعلمين» يلتقيان بما يكتبه المستخدم أيّاً كان رسمُه.

    والدالّةُ نفسُها مكرَّرةٌ في Kotlin (`ArabicSearch.normalize`) وتُطبَّق
    على استعلام المستخدم — والاثنتان يحرسهما `check_quran_data.py`.
    """
    t = unicodedata.normalize("NFC", text)
    t = DIACRITICS.sub("", t)
    t = t.translate(TRANSLATE)
    for src, dst in UTHMANI_TO_IMLAEI.items():
        t = t.replace(src, dst)
    t = t.replace("ا", "")
    #  والمسافاتُ تُحذف كذلك: الرسمُ العثمانيّ يصل كلماتٍ يفصلها الإملائيّ
    #  («يَٰٓأَيُّهَا» يكتبها الناس «يا أيها»)، فلو بقيت المسافةُ فارقةً لما
    #  وُجد أشهرُ نداءٍ في القرآن. والبحثُ متضمَّنٌ (`LIKE %…%`) أصلاً،
    #  فحذفُها يزيد ما يُوجَد ولا يُضيّع شيئاً.
    t = re.sub(r"\s+", "", t)
    return t


def main() -> int:
    rows = json.loads(QURAN.read_text(encoding="utf-8"))

    split = 0
    for r in rows:
        surah = r["surah"]
        # البسملةُ تُقصّ من أوّل آيةٍ فقط، وفي غير الفاتحة والتوبة.
        if r["ayah"] == 1 and surah not in KEEP_WHOLE:
            body = BISMILLAH_RE.sub("", r["text_uthmani"], count=1)
            if body != r["text_uthmani"] and body.strip():
                r["bismillah"] = True
                r["text_uthmani"] = body.strip()
                split += 1
        r.setdefault("bismillah", False)

        # يُعاد بناؤه دائماً حتى يتبع أيَّ تصحيحٍ في المتن.
        r["text_simple"] = searchable(r["text_uthmani"])

    QURAN.write_text(
        json.dumps(rows, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8",
    )

    print(f"آيات: {len(rows)} · بسملةٌ فُصلت الآن: {split} · "
          f"سورٌ لها بسملة: {sum(1 for r in rows if r['bismillah'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
