cities = json.loads(CITIES.read_text())
problems, seen = [], {}

for c in cities:
    name, code = c["ar"], c["country"]
    lat, lng = c["lat"], c["lng"]

    for field in ("ar", "en", "country", "country_ar"):
        if not str(c.get(field, "")).strip():
            problems.append(f"{name}: الحقل {field} فارغ")

    if not (-90 <= lat <= 90):    problems.append(f"{name}: خط عرض خارج المدى ({lat})")
    if not (-180 <= lng <= 180):  problems.append(f"{name}: خط طول خارج المدى ({lng})")

    if code not in BOX:
        problems.append(f"{name}: لا صندوق حدود للبلد {code} — أضِفه قبل إضافة مدنه")
    else:
        la0, la1, ln0, ln1 = BOX[code]
        if not (la0 <= lat <= la1 and ln0 <= lng <= ln1):
            problems.append(
                f"{name} ({code}): الإحداثيات ({lat}, {lng}) خارج صندوق البلد "
                f"[{la0}..{la1}, {ln0}..{ln1}] — تبديل بين الطول والعرض أو إشارة مقلوبة؟")

    for key, label in ((name, "الاسم العربي"), (c["en"], "الاسم الإنجليزي")):
        if key in seen.get(label, ()):
            problems.append(f"{key}: مكرّر في {label}")
        seen.setdefault(label, set()).add(key)

print(f"فُحصت {len(cities)} مدينة في {len({c['country'] for c in cities})} بلداً · مشاكل {len(problems)}")
if problems:
    for p in problems: print("  ✗ " + p)
    sys.exit(1)
