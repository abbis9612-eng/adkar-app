package app.rafiqaldhikr.util

/* ═══════════════════════════════════════════════════════════════════
   الموقع — إمّا معروف أو غير معروف. لا ثالث.

   كان في التطبيق احتياطيّان صامتان: السليمانية (35.5558/45.4436) في سبعة
   مواضع من طبقة الأندرويد، ومكة (21.3891/39.8579) في طبقة المشترك. أي
   مستخدم بلا إذن موقع كان يرى مواقيت مدينةٍ ليست مدينته — معروضةً بثقة،
   بلا أي إشارة إلى أنها ليست له — ويُجدوَل عليها أذانٌ في وقت خاطئ.

   الخطأ هنا ليس تقنياً. عرض وقتِ صلاةٍ خاطئ على أنه صحيح أسوأ من عدم
   عرض شيء، لأن المستخدم يبني عليه عبادة.

   القاعدة الآن: صفر/صفر يعني «لا موقع»، ويعطي null، والواجهة تطلب
   الموقع بدل أن تخمّنه.
═══════════════════════════════════════════════════════════════════ */

data class Coords(val lat: Double, val lng: Double)

/** null = لا موقع محفوظ. لا تستبدله بإحداثية افتراضية. */
fun coordsOrNull(lat: Double, lng: Double): Coords? =
    if (lat == 0.0 && lng == 0.0) null else Coords(lat, lng)
